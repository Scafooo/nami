"""Fig. 2 of the v2 evaluation: one row per list, five columns. Values None draw a placeholder (grey ring, red xx)."""
import sys
OUT = sys.argv[1]
PH = None
# (label, style, worth persons, worth themes, all hold, >=2 reasons, agreed stops); None = placeholder; "-" = no reasons
rows = [("GPT", "model", PH, PH, PH, PH, PH), ("Gemini", "model", PH, PH, PH, PH, PH),
        ("GPT + check", "modelc", PH, PH, PH, PH, PH), ("Gemini + check", "modelc", PH, PH, PH, PH, PH),
        (r"\textbf{Nami}", "nami", PH, PH, PH, PH, PH), ("Nami, Wikidata only", "var", PH, PH, PH, PH, PH),
        ("Nami + GPT", "hyb", PH, PH, PH, PH, PH), ("Nami + Gemini", "hyb", PH, PH, PH, PH, PH),
        ("direct links (Wikidata)", "base", PH, PH, "-", "-", PH), ("pre-packaged tour", "base", PH, PH, "-", "-", PH)]
gaps = {2, 4, 6, 8}
cols = [r"worth a visit, persons (\%)", r"worth a visit, movements and themes (\%)",
        r"places whose reasons all hold (\%)", r"places with two or more reasons (\%)", r"agreed stops found (\%)"]
X0, CW, GAP, DY = 2.75, 1.75, 0.28, 0.33
L = [r"""% Fig. 2 (v2 evaluation). PLACEHOLDER values: generated by make_dots_v2.py; to be filled from results/data/.
\begin{tikzpicture}[font=\fontsize{6.5}{7.5}\selectfont\sffamily,
  model/.style={circle, fill=red!65!black, minimum size=1.9mm, inner sep=0pt},
  modelc/.style={circle, fill=red!30, draw=red!65!black, minimum size=1.9mm, inner sep=0pt},
  nami/.style={circle, fill=orange!70!black, minimum size=1.9mm, inner sep=0pt},
  var/.style={circle, fill=black!40, minimum size=1.9mm, inner sep=0pt},
  hyb/.style={circle, fill=violet!70!black, minimum size=1.9mm, inner sep=0pt},
  base/.style={circle, draw=black!50, fill=white, minimum size=1.7mm, inner sep=0pt},
  ph/.style={circle, draw=black!35, dashed, fill=white, minimum size=1.9mm, inner sep=0pt},
  val/.style={font=\fontsize{5.5}{6.5}\selectfont\sffamily, text=black!65, inner sep=1pt}]"""]
ys, y = [], 0
for i, _ in enumerate(rows):
    if i in gaps:
        y -= 0.12
    ys.append(y)
    y -= DY
ybot = ys[-1] - DY * 0.6
for c, title in enumerate(cols):
    x0 = X0 + c * (CW + GAP)
    f = lambda v: x0 + v / 100 * CW
    L.append(f"\\node[anchor=south, align=center, text width={CW + 0.2:.2f}cm, font=\\fontsize{{6}}{{7}}\\selectfont\\bfseries\\sffamily, text=black!70] at ({x0 + CW / 2:.2f},{DY * 0.6:.2f}) {{{title}}};")
    for t in (0, 50, 100):
        L.append(f"\\draw[black!10] ({f(t):.2f},{DY * 0.5:.2f}) -- ({f(t):.2f},{ybot:.2f}); \\node[anchor=north, val] at ({f(t):.2f},{ybot:.2f}) {{{t}}};")
    for (lab, st, *v), yy in zip(rows, ys):
        val = v[c]
        L.append(f"\\draw[black!25] ({x0:.2f},{yy:.2f}) -- ({x0 + CW:.2f},{yy:.2f});")
        if val == "-":
            L.append(f"\\node[val] at ({x0 + CW / 2:.2f},{yy:.2f}) {{no reasons}};")
        elif val is None:
            L.append(f"\\node[ph] at ({f(50):.2f},{yy:.2f}) {{}}; \\node[val, right=1.5pt, text=red] at ({f(50):.2f},{yy:.2f}) {{\\textbf{{xx}}}};")
        else:
            L.append(f"\\draw[black!45, line width=0.6pt] ({x0:.2f},{yy:.2f}) -- ({f(val):.2f},{yy:.2f}); \\node[{st}] at ({f(val):.2f},{yy:.2f}) {{}}; \\node[val, right=1.5pt] at ({f(val):.2f},{yy:.2f}) {{{val:.0f}}};")
for (lab, st, *v), yy in zip(rows, ys):
    L.append(f"\\node[{st}] at ({X0 - 0.15:.2f},{yy:.2f}) {{}}; \\node[anchor=east] at ({X0 - 0.3:.2f},{yy:.2f}) {{{lab}}};")
L.append(r"\end{tikzpicture}")
open(OUT, "w").write("\n".join(L) + "\n")
